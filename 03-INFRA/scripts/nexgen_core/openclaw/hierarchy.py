"""Who each agent answers to, who answers to it, and who stands beside it.

One job: derive one agent's place in the roster -- its lead, the agents that
report to it and its peers -- from the agents that exist and the `reportsTo` a
squad declares, and render the managed block that says so. Why: an agent has to
know whom to delegate to and whom to report to, and that answer belongs to the
roster as data, not to a list of names written into every template.

A squad may declare `reportsTo: <agent id>`; without it the roster's own shape
decides, and a declaration the roster cannot honour is reported and ignored
rather than written into a manual as a lead that does not exist.

Nothing here reads a file, an environment variable or a clock: the roster
arrives as ids and the declarations as a mapping, exactly like `profile.py`.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any

from nexgen_core.i18n import detect_language, t
from nexgen_core.openclaw.tools_profile import SUPERVISOR_AGENT

#: The agent that faces the person, so it reports to nobody inside the roster.
PERSON_FACING_AGENT = "main"

#: The roster the engine creates when no squad declares one, in the order the
#: agents are introduced. A manual rendered with no roster says this one.
DEFAULT_ROSTER: tuple[str, ...] = ("main", SUPERVISOR_AGENT, "automazioni", "sviluppo")

#: The heading of the managed block that carries this section in each workspace
#: `AGENTS.md`. The guard writes the block, so the shipped manual body stays
#: roster-independent and the chart reaches a workspace that already exists.
ORG_BLOCK_TITLE = {"it": "Organigramma", "en": "Org chart"}

#: The first line of the block: what it is, and that it overrides the lists of
#: names an older manual wrote by hand.
_NOTICE = {
    "it": "Questo blocco è generato dal motore a partire dalla squadra e sostituisce\n"
          "qualsiasi elenco di destinatari possibili scritto altrove in questo file.",
    "en": "This block is generated by the engine from the squad and replaces any list\n"
          "of possible recipients written elsewhere in this file.",
}

_RULES: dict[str, str] = {
    "it": """- Chiunque può scrivere a chiunque con `sessions_send`: la gerarchia dice
  verso chi delegare e a chi riportare, non chi può parlare.
- Delega un compito verso il basso, allo specialista che lo possiede; riporta il
  risultato e porta i blocchi verso l'alto, al tuo responsabile.
- Chiedi a un pari l'informazione che ti serve, direttamente.
- Il lavoro supervisionato che cambia lo stato del motore passa dai tool `sup`
  del supervisore.""",
    "en": """- Anyone may write to anyone with `sessions_send`: the hierarchy says whom to
  delegate to and whom to report to, not who may talk.
- Delegate a task downwards, to the specialist who owns it; report the result
  and escalate blockers upwards, to your lead.
- Ask a peer for the information you need, directly.
- Supervised work that changes the engine's state goes through the supervisor's
  `sup` tools.""",
}

_PLACES = {
    "it": {
        "lead": "Il tuo responsabile: {values}.",
        "lead_nobody": "Il tuo responsabile: nessuno, rispondi alla persona.",
        "reports": "Riportano a te: {values}.",
        "peers": "I tuoi pari: {values}.",
        "nobody": "nessuno",
    },
    "en": {
        "lead": "Your lead: {values}.",
        "lead_nobody": "Your lead: nobody, you answer to the person.",
        "reports": "Reporting to you: {values}.",
        "peers": "Your peers: {values}.",
        "nobody": "nobody",
    },
}


@dataclass(frozen=True)
class Place:
    """One agent's place in the roster."""

    #: The agent this one reports to, or None when it answers to the person.
    lead: str | None
    #: The agents that report to this one, sorted.
    reports: tuple[str, ...]
    #: The agents under the same lead, sorted.
    peers: tuple[str, ...]


def _language(lang: str | None) -> str:
    """`it` or `en`: anything else reads the language the engine speaks."""
    chosen = (lang or detect_language() or "en").strip().lower()
    return "it" if chosen.startswith("it") else "en"


def manual_language(text: str | None) -> str | None:
    """The language an `AGENTS.md` is written in, when one of its headings says so.

    The guard rewrites the block in the language of the manual around it, not the
    machine's: an English workspace must not grow an Italian chart on a laptop set
    to Italian. A file with none of the known headings says nothing, and the
    caller falls back to the language the engine speaks.
    """
    markers = {
        "it": ("## Chi sei", "## Organigramma"),
        "en": ("## Who you are", "## Org chart"),
    }
    for language, headings in markers.items():
        if any(heading in (text or "") for heading in headings):
            return language
    return None


def _roster(roster: Iterable[str] | Mapping[str, Any] | None) -> tuple[str, ...]:
    """The ids that exist, without duplicates: a mapping contributes its keys."""
    if roster is None:
        return DEFAULT_ROSTER
    values = roster.keys() if isinstance(roster, Mapping) else roster
    return tuple(dict.fromkeys(str(item) for item in values if str(item).strip()))


def declared_leads(squad: Mapping[str, Any] | None) -> dict[str, str]:
    """The `reportsTo` each agent declares in the squad, by agent id.

    A field that is not a non-empty string is ignored, not guessed: the agent
    keeps the lead the roster's shape gives it.
    """
    agents = squad.get("agents") if isinstance(squad, Mapping) else None
    if not isinstance(agents, Mapping):
        return {}
    leads: dict[str, str] = {}
    for agent_id, spec in agents.items():
        value = spec.get("reportsTo") if isinstance(spec, Mapping) else None
        if isinstance(value, str) and value.strip():
            leads[str(agent_id)] = value.strip()
    return leads


def default_lead(agent_id: str, roster: Iterable[str]) -> str | None:
    """The lead an agent has when the squad declares none.

    The person-facing agent has none by definition; the supervisor answers to
    the person-facing agent; every other agent answers to the supervisor, or to
    the person-facing agent when the roster has no supervisor, or to nobody.
    """
    present = set(roster)
    if agent_id == PERSON_FACING_AGENT:
        return None
    candidates = (PERSON_FACING_AGENT,) if agent_id == SUPERVISOR_AGENT else (
        SUPERVISOR_AGENT, PERSON_FACING_AGENT,
    )
    for candidate in candidates:
        if candidate in present:
            return candidate
    return None


def _closes_a_loop(agent_id: str, leads: Mapping[str, str | None]) -> bool:
    """Whether following the leads from this agent comes back to it."""
    seen = {agent_id}
    current = leads.get(agent_id)
    while current is not None:
        if current in seen:
            return True
        seen.add(current)
        current = leads.get(current)
    return False


def derive(
    roster: Iterable[str] | Mapping[str, Any] | None = None,
    declared: Mapping[str, str] | None = None,
) -> tuple[dict[str, Place], tuple[str, ...]]:
    """Every agent's place, and the declarations that had to fall back.

    The declarations are applied in id order so one broken squad always derives
    the same hierarchy: a `reportsTo` that names nobody on the roster, or one
    that closes a loop, is reported and replaced by the agent's default lead.
    """
    present = _roster(roster)
    leads: dict[str, str | None] = {agent: default_lead(agent, present) for agent in present}
    errors: list[str] = []
    for agent in sorted(present):
        wanted = (declared or {}).get(agent)
        if not wanted or wanted == leads[agent]:
            continue
        if wanted not in present:
            errors.append(t(
                "The squad makes {agent} report to {lead}, which is not an agent this installation "
                "declares: {agent} keeps its default lead.",
                agent=agent, lead=wanted,
            ))
            continue
        leads[agent] = wanted
        if _closes_a_loop(agent, leads):
            leads[agent] = default_lead(agent, present)
            errors.append(t(
                "The squad makes {agent} report to {lead}, which closes a loop: "
                "{agent} keeps its default lead.",
                agent=agent, lead=wanted,
            ))
    reports: dict[str, list[str]] = {agent: [] for agent in present}
    for agent, lead in leads.items():
        if lead is not None:
            reports[lead].append(agent)
    places = {
        agent: Place(
            lead=leads[agent],
            reports=tuple(sorted(reports[agent])),
            peers=tuple(sorted(
                other for other in present
                if other != agent and leads[other] == leads[agent]
            )),
        )
        for agent in present
    }
    return places, tuple(errors)


def roster_notes(squad: Mapping[str, Any] | None, config: Mapping[str, Any]) -> tuple[str, ...]:
    """What a squad asked of the roster and the roster cannot honour, as the plan says it.

    Two things are reported before anything is written: a default agent the squad
    names without declaring it, and a `reportsTo` that names no agent here or that
    closes a loop. Both fall back to the lead the roster's shape gives, so no
    manual and no plan ever promises a lead that does not exist.
    """
    from nexgen_core.openclaw.squad import unresolved_default

    unknown = unresolved_default(squad)
    notes: list[str] = []
    if unknown:
        notes.append(t(
            "The squad names {agent} as the default agent but does not declare it: no default was written.",
            agent=unknown,
        ))
    agents = config.get("agents") if isinstance(config.get("agents"), dict) else None
    entries = agents.get("entries") if isinstance(agents, dict) else None
    _places, errors = derive(tuple(entries or ()), declared_leads(squad))
    return (*notes, *errors)


def _place_line(template: str, values: Iterable[str], empty: str) -> str:
    """One of the three lines, with the ids named or the word for nobody."""
    named = ", ".join(f"`{value}`" for value in values)
    return template.format(values=named or empty)


def render_org_section(
    agent_id: str,
    lang: str | None,
    roster: Iterable[str] | Mapping[str, Any] | None = None,
    declared: Mapping[str, str] | None = None,
) -> str:
    """One agent's place in the block: its lead, its reports and its peers."""
    language = _language(lang)
    places, _errors = derive(roster, declared)
    place = places.get(agent_id, Place(lead=None, reports=(), peers=()))
    words = _PLACES[language]
    if place.lead is None:
        lead = words["lead_nobody"]
    else:
        lead = _place_line(words["lead"], (place.lead,), words["nobody"])
    return "\n".join([
        f"### `{agent_id}`",
        "",
        lead,
        _place_line(words["reports"], place.reports, words["nobody"]),
        _place_line(words["peers"], place.peers, words["nobody"]),
    ])


def _roster_order(agents: Iterable[str], roster: Iterable[str] | None) -> tuple[str, ...]:
    """The agents in the roster's own order, with any id it does not name at the end."""
    chosen = _roster(agents)
    known = _roster(roster) if roster is not None else chosen
    return tuple(
        [agent for agent in known if agent in chosen]
        + [agent for agent in chosen if agent not in known]
    )


def render_org_block(
    agents: Iterable[str],
    lang: str | None,
    roster: Iterable[str] | Mapping[str, Any] | None = None,
    declared: Mapping[str, str] | None = None,
) -> str:
    """The whole org chart for one workspace: the rule and one section per agent.

    A workspace several agents share gets one section each, in roster order, so
    the answer never depends on which entry the config happened to list first.
    """
    language = _language(lang)
    present = _roster(roster) if roster is not None else _roster(agents)
    parts = [
        f"## {ORG_BLOCK_TITLE[language]}",
        "",
        _NOTICE[language],
        "",
        _RULES[language],
    ]
    for agent_id in _roster_order(agents, present):
        parts.extend(["", render_org_section(agent_id, language, present, declared)])
    return "\n".join(parts)
