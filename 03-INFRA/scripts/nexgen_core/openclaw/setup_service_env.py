"""Service environment file for OpenClaw gateway.

One job: calculate variables referenced in OpenClaw config and mounted MCP
servers, write ~/.openclaw/gateway.systemd.env with mode 0600, and register
the systemd user drop-in unit.
"""
from __future__ import annotations

import os
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import TYPE_CHECKING, Any

from nexgen_core.i18n import t

if TYPE_CHECKING:
    from nexgen_core.openclaw.setup_steps import Setup

_VAR_PATTERN = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")
_SIMPLE_VAR_PATTERN = re.compile(r"(?<!\\)\$([A-Za-z_][A-Za-z0-9_]*)")

_KNOWN_MODEL_ENV_VARS = {
    "anthropic": ["ANTHROPIC_API_KEY"],
    "openai": ["OPENAI_API_KEY"],
    "deepseek": ["DEEPSEEK_API_KEY"],
    "opencode": ["OPENCODE_GO_KEY"],
    "google": ["GEMINI_API_KEY", "GOOGLE_API_KEY"],
    "brave": ["BRAVE_API_KEY"],
}


def _extract_vars_from_val(val: Any, found: set[str]) -> None:
    if isinstance(val, str):
        for m in _VAR_PATTERN.findall(val):
            found.add(m)
        for m in _SIMPLE_VAR_PATTERN.findall(val):
            found.add(m)
    elif isinstance(val, dict):
        for k, v in val.items():
            if str(k).lower() == "env" and isinstance(v, dict):
                for env_k in v.keys():
                    if isinstance(env_k, str):
                        found.add(env_k)
            _extract_vars_from_val(v, found)
    elif isinstance(val, (list, tuple, set)):
        for item in val:
            _extract_vars_from_val(item, found)


def extract_referenced_env_vars(config: dict[str, Any]) -> set[str]:
    """Inspects OpenClaw config and MCP servers to find all cited env vars."""
    found: set[str] = set()
    _extract_vars_from_val(config, found)

    # Check agents' models for known model provider env vars
    agents = config.get("agents", {}).get("entries", {}) if isinstance(config.get("agents"), dict) else {}
    for entry in agents.values():
        if isinstance(entry, dict):
            model = str(entry.get("model") or "").lower()
            for provider, vars_list in _KNOWN_MODEL_ENV_VARS.items():
                if provider in model:
                    found.update(vars_list)
    return found


def _format_env_line(key: str, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'{key}="{escaped}"'


def write_gateway_service_env(
    setup: Setup,
    config: dict[str, Any],
    systemd_user_dir: Path | None = None,
) -> Path | None:
    """Calculates cited env vars, writes gateway.systemd.env (0600) and systemd drop-in."""
    referenced = extract_referenced_env_vars(config)
    env_source: Mapping[str, str] = setup.env or os.environ
    active_vars = {k: env_source[k] for k in sorted(referenced) if k in env_source and env_source[k]}

    env_file = setup.state_dir / "gateway.systemd.env"
    lines = [
        "# Generated by NeXgen Engine for OpenClaw gateway service",
        "# Only variables referenced in configuration and mounted MCP servers",
        *[_format_env_line(k, v) for k, v in active_vars.items()],
        "",
    ]
    env_file.parent.mkdir(parents=True, exist_ok=True)
    env_file.write_text("\n".join(lines), encoding="utf-8")
    if (setup.platform or sys.platform) != "win32":
        try:
            env_file.chmod(0o600)
        except OSError:  # nexgen: allow reason="chmod failures on filesystems without POSIX permissions are ignored"
            pass

    setup.out(t("Gateway service environment written to {path} ({count} variables).",
                path=env_file, count=len(active_vars)))

    user_dir = systemd_user_dir or (setup.home / ".config" / "systemd" / "user")
    if user_dir.is_dir() or (setup.platform or sys.platform) == "linux":
        dropin_dir = user_dir / "openclaw-gateway.service.d"
        dropin_dir.mkdir(parents=True, exist_ok=True)
        dropin_file = dropin_dir / "10-env.conf"
        dropin_content = (
            "[Service]\n"
            f"EnvironmentFile=%h/{env_file.relative_to(setup.home).as_posix() if env_file.is_relative_to(setup.home) else str(env_file)}\n"
        )
        dropin_file.write_text(dropin_content, encoding="utf-8")
        if setup.which("systemctl"):
            setup.run(["systemctl", "--user", "daemon-reload"], setup.env)

    return env_file
